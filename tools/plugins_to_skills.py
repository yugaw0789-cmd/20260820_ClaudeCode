#!/usr/bin/env python3
"""Convert anthropics/claude-plugins-official into Claude Code skills.

The upstream repository ships its capabilities as *plugins*: each plugin bundles
some mix of `skills/`, `commands/` (slash commands) and `agents/` (subagents).
Only the `skills/` part is directly usable as a skill; commands and agents use
their own file formats and their own frontmatter fields.

This script flattens all three into `.claude/skills/<slug>/SKILL.md` so every
capability in the directory is reachable as a skill in this repository, and
copies the plugin-level assets that converted files refer to through
`${CLAUDE_PLUGIN_ROOT}` into `.claude/plugin-skills/vendor/<plugin>/`.

Usage:
    python3 tools/plugins_to_skills.py            # clone upstream, regenerate
    python3 tools/plugins_to_skills.py --source /path/to/clone
    python3 tools/plugins_to_skills.py --check    # validate what is committed
    python3 tools/plugins_to_skills.py --help
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

UPSTREAM_URL = "https://github.com/anthropics/claude-plugins-official.git"

REPO_ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = REPO_ROOT / ".claude" / "skills"
BUNDLE_DIR = REPO_ROOT / ".claude" / "plugin-skills"
VENDOR_DIR = BUNDLE_DIR / "vendor"
MANIFEST_PATH = BUNDLE_DIR / "manifest.json"

GENERATED_MARKER = "<!-- generated by tools/plugins_to_skills.py -->"

# Frontmatter keys that mean something to a skill. Everything else upstream
# carries (`model`, `color`, ...) is agent/command-only and is reported in the
# provenance note instead of being emitted as a skill field.
SKILL_FIELDS = (
    "description",
    "argument-hint",
    "allowed-tools",
    "disable-model-invocation",
    "user-invocable",
    "license",
    "version",
)

NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
MAX_NAME = 64
MAX_DESCRIPTION = 1024

# Plugin-level directories vendored for `${CLAUDE_PLUGIN_ROOT}` lookups. The
# component directories are skipped: their contents become skills of their own.
VENDOR_SKIP_DIRS = {".git", ".github", "skills", "commands", "agents"}
IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".gif", ".webp"}


# --------------------------------------------------------------------------
# Minimal YAML frontmatter reader
# --------------------------------------------------------------------------


def split_frontmatter(text: str) -> tuple[str, str]:
    """Return (frontmatter, body). Frontmatter is '' when the file has none."""
    if not text.startswith("---"):
        return "", text
    lines = text.split("\n")
    for i in range(1, len(lines)):
        if lines[i].rstrip() == "---":
            return "\n".join(lines[1:i]), "\n".join(lines[i + 1 :])
    return "", text


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        inner = value[1:-1]
        if value[0] == '"':
            return (
                inner.replace("\\n", "\n")
                .replace("\\t", "\t")
                .replace('\\"', '"')
                .replace("\\\\", "\\")
            )
        return inner.replace("''", "'")
    return value


def _parse_flow_list(value: str) -> list[str]:
    inner = value.strip()[1:-1]
    return [_unquote(part) for part in inner.split(",") if part.strip()]


def parse_frontmatter(text: str) -> dict[str, object]:
    """Parse the subset of YAML the upstream plugin files actually use.

    Supports `key: scalar`, quoted scalars continued over indented lines, block
    sequences (`- item`) and flow sequences (`[a, b]`). Anything more exotic is
    returned as the raw joined string, which is enough for the fields we read.
    """
    data: dict[str, object] = {}
    lines = split_frontmatter(text)[0].split("\n") if text.startswith("---") else text.split("\n")

    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        match = re.match(r"^([A-Za-z0-9_.-]+):\s*(.*)$", line)
        if not match:
            continue
        key, rest = match.group(1), match.group(2).strip()

        if rest.startswith("[") and rest.endswith("]"):
            data[key] = _parse_flow_list(rest)
            continue

        if re.fullmatch(r"[|>][-+]?\d*", rest):
            # Block scalar: everything indented below the key belongs to it.
            block: list[str] = []
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith((" ", "\t"))):
                block.append(lines[i])
                i += 1
            while block and not block[-1].strip():
                block.pop()
            indent = min(
                (len(b) - len(b.lstrip()) for b in block if b.strip()), default=0
            )
            joiner = "\n" if rest[0] == "|" else " "
            data[key] = joiner.join(b[indent:] for b in block).strip()
            continue

        if not rest:
            items: list[str] = []
            while i < len(lines) and lines[i].lstrip().startswith("- "):
                items.append(_unquote(lines[i].lstrip()[2:]))
                i += 1
            if items:
                data[key] = items
                continue
            # A key with an indented scalar underneath (folded description).
            chunks: list[str] = []
            while i < len(lines) and lines[i].startswith((" ", "\t")) and lines[i].strip():
                chunks.append(lines[i].strip())
                i += 1
            if chunks:
                data[key] = _unquote(" ".join(chunks))
            continue

        # Scalar, possibly continued on following indented lines.
        chunks = [rest]
        while i < len(lines) and lines[i].startswith((" ", "\t")) and lines[i].strip():
            if re.match(r"^\s+-\s", lines[i]):
                break
            chunks.append(lines[i].strip())
            i += 1
        data[key] = _unquote(" ".join(chunks))

    return data


def emit_frontmatter(fields: list[tuple[str, object]]) -> str:
    """Render frontmatter using JSON scalars, which are always valid YAML."""
    out = ["---"]
    for key, value in fields:
        if value is None:
            continue
        if isinstance(value, bool):
            out.append(f"{key}: {'true' if value else 'false'}")
        elif isinstance(value, list):
            items = ", ".join(json.dumps(str(v), ensure_ascii=False) for v in value)
            out.append(f"{key}: [{items}]")
        else:
            out.append(f"{key}: {json.dumps(str(value), ensure_ascii=False)}")
    out.append("---")
    return "\n".join(out)


# --------------------------------------------------------------------------
# Source discovery
# --------------------------------------------------------------------------


@dataclass
class Source:
    kind: str  # "skill" | "command" | "agent"
    plugin: str
    plugin_dir: Path
    path: Path  # the SKILL.md / command .md / agent .md
    base: str  # directory name (skills) or file stem (commands, agents)
    rel: str = ""  # path relative to the upstream checkout
    slug: str = ""
    meta: dict[str, object] = field(default_factory=dict)


def discover(root: Path, include_external: bool, kinds: set[str]) -> list[Source]:
    plugin_roots: list[Path] = []
    for group in ("plugins", "external_plugins"):
        if group == "external_plugins" and not include_external:
            continue
        group_dir = root / group
        if group_dir.is_dir():
            plugin_roots += sorted(p for p in group_dir.iterdir() if p.is_dir())

    found: list[Source] = []
    for plugin_dir in plugin_roots:
        plugin = plugin_dir.name

        if "skill" in kinds:
            for skill_md in sorted((plugin_dir / "skills").glob("*/SKILL.md")):
                found.append(
                    Source("skill", plugin, plugin_dir, skill_md, skill_md.parent.name)
                )
        if "command" in kinds:
            for cmd in sorted((plugin_dir / "commands").glob("*.md")):
                found.append(Source("command", plugin, plugin_dir, cmd, cmd.stem))
        if "agent" in kinds:
            for agent in sorted((plugin_dir / "agents").glob("*.md")):
                found.append(Source("agent", plugin, plugin_dir, agent, agent.stem))

    for source in found:
        source.rel = str(source.path.relative_to(root))
        source.meta = parse_frontmatter(source.path.read_text(encoding="utf-8"))
    return found


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return re.sub(r"-{2,}", "-", slug)


def assign_slugs(sources: list[Source]) -> None:
    """Namespace each capability by plugin, collapsing `foo/foo` to `foo`."""
    taken: dict[str, Source] = {}
    order = {"skill": 0, "command": 1, "agent": 2}
    suffix = {"skill": "skill", "command": "cmd", "agent": "agent"}
    for source in sorted(sources, key=lambda s: (order[s.kind], s.plugin, s.base)):
        plugin, base = slugify(source.plugin), slugify(source.base)
        slug = base if base == plugin else f"{plugin}-{base}"

        if slug in taken:
            slug = f"{slug}-{suffix[source.kind]}"
        n = 2
        while slug in taken:
            slug = f"{slug}-{n}"
            n += 1

        source.slug = slug[:MAX_NAME].rstrip("-")
        taken[source.slug] = source


# --------------------------------------------------------------------------
# Conversion
# --------------------------------------------------------------------------


def split_examples(description: str) -> tuple[str, str]:
    """Separate a description's trigger sentences from its worked examples.

    Several upstream agents embed `<example>` transcripts in the description,
    which is how an agent advertises itself for delegation. A skill description
    is only a trigger string — the transcripts belong in the body.
    """
    candidates = [
        m.start()
        for m in (
            re.search(r"<example>", description, re.IGNORECASE),
            re.search(r"(?:^|\s)Examples?:\s", description),
        )
        if m
    ]
    if not candidates:
        return description, ""
    cut = min(candidates)
    prefix, examples = description[:cut].strip(), description[cut:].strip()
    if len(prefix) < 80 or not examples:
        return description, ""
    return prefix, examples


def shorten(text: str, limit: int) -> str:
    """Trim to `limit` at a sentence break, falling back to a word break."""
    if len(text) <= limit:
        return text
    head = text[: limit - 1]
    sentence = max(head.rfind(". "), head.rfind("? "), head.rfind("! "))
    if sentence > limit // 2:
        return head[: sentence + 1]
    word = head.rfind(" ")
    return (head[:word] if word > limit // 2 else head).rstrip(" ,;:-") + "…"


def fallback_description(source: Source) -> str:
    noun = {"skill": "skill", "command": "slash command", "agent": "subagent"}[source.kind]
    return (
        f"{source.base.replace('-', ' ').capitalize()} — {noun} from the "
        f"{source.plugin} plugin of claude-plugins-official."
    )


def provenance(source: Source, upstream_ref: str) -> str:
    vendor_ref = f"`.claude/plugin-skills/vendor/{source.plugin}/`"
    lines = [
        GENERATED_MARKER,
        "",
        f"> Converted from [`{source.rel}`](https://github.com/anthropics/claude-plugins-official/blob/{upstream_ref}/{source.rel})",
        f"> in the `{source.plugin}` plugin of `anthropics/claude-plugins-official` (Apache-2.0).",
    ]

    if source.kind == "command":
        lines += [
            ">",
            "> **This was a slash command.** Claude Code preprocesses command files;"
            " a skill body is not preprocessed, so read the placeholders below yourself:",
            "> `$ARGUMENTS` / `$1`, `$2` are whatever the user asked for when invoking this skill,"
            " `` !`cmd` `` is a shell command to run with Bash before continuing,"
            " and `@path` means read that file.",
        ]
    elif source.kind == "agent":
        model = source.meta.get("model")
        detail = f" Upstream ran it on `model: {model}`." if model else ""
        lines += [
            ">",
            "> **This was a subagent definition.** The body is written as a system prompt"
            f" — follow it as your operating instructions for this task.{detail}",
            "> Delegate it to a subagent with the Agent tool when the work is large enough to be worth isolating.",
        ]

    if "${CLAUDE_PLUGIN_ROOT}" in source.path.read_text(encoding="utf-8"):
        lines += [
            ">",
            f"> `${{CLAUDE_PLUGIN_ROOT}}` below resolves to {vendor_ref} in this repository"
            " (except where the text is *teaching* you to write plugins — there it is literal).",
        ]

    return "\n".join(lines)


def build_skill_md(source: Source, upstream_ref: str) -> str:
    raw = source.path.read_text(encoding="utf-8")
    body = split_frontmatter(raw)[1].lstrip("\n")

    description = str(source.meta.get("description") or "").strip()
    if not description:
        description = fallback_description(source)
    # A few upstream descriptions are plain scalars carrying literal `\n`
    # escapes rather than real line breaks.
    description = description.replace("\\n", "\n")

    description, examples = split_examples(description)
    if examples:
        description += ' See "When to invoke" below for worked scenarios.'
        body = f"## When to invoke\n\n{examples}\n\n{body}"
    description = shorten(re.sub(r"\s+", " ", description), MAX_DESCRIPTION)

    fields: list[tuple[str, object]] = [("name", source.slug), ("description", description)]

    allowed = source.meta.get("allowed-tools") or source.meta.get("tools")
    if isinstance(allowed, str):
        allowed = [part.strip() for part in allowed.split(",") if part.strip()]
    if allowed:
        fields.append(("allowed-tools", allowed))

    for key in ("argument-hint", "license", "version"):
        value = source.meta.get(key)
        if value:
            fields.append((key, value))
    for key in ("disable-model-invocation", "user-invocable"):
        value = source.meta.get(key)
        if isinstance(value, str):
            fields.append((key, value.strip().lower() == "true"))

    return f"{emit_frontmatter(fields)}\n\n{provenance(source, upstream_ref)}\n\n{body.rstrip()}\n"


def copy_skill_resources(source: Source, target: Path) -> None:
    """Copy a skill directory's sibling files (references/, scripts/, ...)."""
    for item in sorted(source.path.parent.iterdir()):
        if item.name == "SKILL.md":
            continue
        destination = target / item.name
        if item.is_dir():
            shutil.copytree(item, destination, dirs_exist_ok=True)
        else:
            shutil.copy2(item, destination)


def vendor_plugin(plugin_dir: Path, destination: Path) -> bool:
    """Copy plugin-level assets referenced through `${CLAUDE_PLUGIN_ROOT}`."""
    copied = False
    for item in sorted(plugin_dir.iterdir()):
        if item.name in VENDOR_SKIP_DIRS:
            continue
        # Top-level images are README screenshots; they are not referenced by
        # any skill body and dominate the upstream repository's size.
        if item.is_file() and item.suffix.lower() in IMAGE_SUFFIXES:
            continue
        destination.mkdir(parents=True, exist_ok=True)
        if item.is_dir():
            shutil.copytree(item, destination / item.name, dirs_exist_ok=True)
        else:
            shutil.copy2(item, destination / item.name)
        copied = True
    return copied


# --------------------------------------------------------------------------
# Validation
# --------------------------------------------------------------------------


def validate(skills_dir: Path) -> list[str]:
    problems: list[str] = []
    seen: dict[str, Path] = {}

    for skill_md in sorted(skills_dir.glob("*/SKILL.md")):
        directory = skill_md.parent.name
        meta = parse_frontmatter(skill_md.read_text(encoding="utf-8"))
        name = str(meta.get("name") or "")
        description = str(meta.get("description") or "")

        if not name:
            problems.append(f"{directory}: missing `name`")
        elif name != directory:
            problems.append(f"{directory}: `name: {name}` does not match the directory")
        elif not NAME_RE.match(name):
            problems.append(f"{directory}: `name` must be lowercase words joined by hyphens")
        elif len(name) > MAX_NAME:
            problems.append(f"{directory}: `name` is longer than {MAX_NAME} characters")

        if not description:
            problems.append(f"{directory}: missing `description`")
        elif len(description) > MAX_DESCRIPTION:
            problems.append(f"{directory}: `description` is longer than {MAX_DESCRIPTION} characters")

        if name in seen:
            problems.append(f"{directory}: duplicate skill name (also {seen[name].parent.name})")
        seen[name] = skill_md

    nested = [p for p in skills_dir.glob("*/*/**/SKILL.md")]
    for path in nested:
        problems.append(f"{path.relative_to(skills_dir)}: nested SKILL.md would register twice")

    return problems


# --------------------------------------------------------------------------
# Driver
# --------------------------------------------------------------------------


def clone_upstream(ref: str, into: Path) -> Path:
    checkout = into / "claude-plugins-official"
    subprocess.run(
        ["git", "clone", "--depth", "1", "--branch", ref, UPSTREAM_URL, str(checkout)],
        check=True,
        stdout=subprocess.DEVNULL,
    )
    return checkout


def git_sha(repo: Path) -> str:
    try:
        return subprocess.run(
            ["git", "-C", str(repo), "rev-parse", "HEAD"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip()
    except subprocess.CalledProcessError:
        return "unknown"


def generate(args: argparse.Namespace) -> int:
    kinds = {"skill"}
    if not args.no_commands:
        kinds.add("command")
    if not args.no_agents:
        kinds.add("agent")

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(args.source).resolve() if args.source else clone_upstream(args.ref, Path(tmp))
        if not (root / "plugins").is_dir():
            print(f"error: {root} does not look like claude-plugins-official", file=sys.stderr)
            return 1

        sha = git_sha(root)
        sources = discover(root, include_external=not args.no_external, kinds=kinds)
        if args.only:
            wanted = set(args.only)
            sources = [s for s in sources if s.plugin in wanted]
        if args.exclude:
            unwanted = set(args.exclude)
            sources = [s for s in sources if s.plugin not in unwanted]
        if not sources:
            print("error: no plugins matched the filters", file=sys.stderr)
            return 1

        assign_slugs(sources)

        if SKILLS_DIR.exists():
            for existing in sorted(SKILLS_DIR.glob("*/SKILL.md")):
                if GENERATED_MARKER in existing.read_text(encoding="utf-8"):
                    shutil.rmtree(existing.parent)
        shutil.rmtree(VENDOR_DIR, ignore_errors=True)
        SKILLS_DIR.mkdir(parents=True, exist_ok=True)
        BUNDLE_DIR.mkdir(parents=True, exist_ok=True)

        entries = []
        vendored: set[str] = set()
        for source in sorted(sources, key=lambda s: s.slug):
            target = SKILLS_DIR / source.slug
            target.mkdir(parents=True, exist_ok=True)
            if source.kind == "skill":
                copy_skill_resources(source, target)
            (target / "SKILL.md").write_text(
                build_skill_md(source, args.ref), encoding="utf-8"
            )

            if source.plugin not in vendored:
                if vendor_plugin(source.plugin_dir, VENDOR_DIR / source.plugin):
                    vendored.add(source.plugin)

            entries.append(
                {
                    "skill": source.slug,
                    "kind": source.kind,
                    "plugin": source.plugin,
                    "source": source.rel,
                }
            )

        shutil.copy2(root / "LICENSE", BUNDLE_DIR / "UPSTREAM_LICENSE")
        MANIFEST_PATH.write_text(
            json.dumps(
                {
                    "upstream": {
                        "repository": "anthropics/claude-plugins-official",
                        "url": UPSTREAM_URL.removesuffix(".git"),
                        "ref": args.ref,
                        "commit": sha,
                        "license": "Apache-2.0",
                    },
                    "generator": "tools/plugins_to_skills.py",
                    "counts": {
                        kind: sum(1 for e in entries if e["kind"] == kind)
                        for kind in ("skill", "command", "agent")
                    },
                    "vendored_plugins": sorted(vendored),
                    "skills": entries,
                },
                indent=2,
                ensure_ascii=False,
            )
            + "\n",
            encoding="utf-8",
        )

    problems = validate(SKILLS_DIR)
    for problem in problems:
        print(f"invalid: {problem}", file=sys.stderr)

    counts = {kind: sum(1 for e in entries if e["kind"] == kind) for kind in ("skill", "command", "agent")}
    print(
        f"generated {len(entries)} skills into {SKILLS_DIR.relative_to(REPO_ROOT)} "
        f"(skills={counts['skill']}, commands={counts['command']}, agents={counts['agent']}) "
        f"from {sha[:12]}"
    )
    return 1 if problems else 0


def check(_: argparse.Namespace) -> int:
    if not SKILLS_DIR.is_dir():
        print(f"error: {SKILLS_DIR} does not exist — run without --check first", file=sys.stderr)
        return 1
    problems = validate(SKILLS_DIR)
    for problem in problems:
        print(f"invalid: {problem}", file=sys.stderr)
    total = len(list(SKILLS_DIR.glob("*/SKILL.md")))
    print(f"checked {total} skills — {len(problems)} problem(s)")
    return 1 if problems else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", help="path to an existing claude-plugins-official checkout")
    parser.add_argument("--ref", default="main", help="upstream branch or tag to clone (default: main)")
    parser.add_argument("--only", nargs="+", metavar="PLUGIN", help="convert only these plugins")
    parser.add_argument("--exclude", nargs="+", metavar="PLUGIN", help="skip these plugins")
    parser.add_argument("--no-external", action="store_true", help="skip external_plugins/")
    parser.add_argument("--no-commands", action="store_true", help="do not convert slash commands")
    parser.add_argument("--no-agents", action="store_true", help="do not convert subagents")
    parser.add_argument("--check", action="store_true", help="validate the committed skills and exit")
    args = parser.parse_args()

    return check(args) if args.check else generate(args)


if __name__ == "__main__":
    sys.exit(main())
